/**
 * 取词助手：返回 (key, vars) => 文案。
 * @param locale - 'zh' | 'en'。
 */
function makeT(locale) {
  const dict = locale === 'en' ? MESSAGES.en : MESSAGES.zh
  return (key, vars) => {
    let text = dict[key] ?? MESSAGES.zh[key] ?? key
    if (vars) for (const name of Object.keys(vars)) text = text.split('{' + name + '}').join(String(vars[name]))
    return text
  }
}

/**
 * 解析生效语言：配置显式指定时优先，否则按浏览器语言。
 * @param configLocale - 'auto' | 'zh' | 'en'。
 */
function resolveLocale(configLocale) {
  if (configLocale === 'zh' || configLocale === 'en') return configLocale
  const nav = typeof navigator === 'undefined' ? '' : String(navigator.language ?? '')
  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

module.exports = { MESSAGES, makeT, resolveLocale }
